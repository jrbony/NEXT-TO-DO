const KEY = 'ntd-language';
let lang = localStorage.getItem(KEY) || 'en';
const orig = new WeakMap();

export const getLang = () => lang;
export const tr = (s) => (lang === 'bn' && bn[s] ? bn[s] : s);
export const catLabel = (k) => (CAT[k] ? tr(CAT[k]) : '—');

export function setLang(next) {
  lang = next === 'bn' ? 'bn' : 'en';
  localStorage.setItem(KEY, lang);
  run();
}

function run() {
  document.documentElement.lang = lang;

  const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = w.nextNode())) {
    const p = n.parentElement;
    if (!p || ['SCRIPT', 'STYLE', 'TEXTAREA'].includes(p.tagName)) continue;

    if (!orig.has(n)) {
      const t = n.nodeValue.trim();
      if (!t || !bn[t]) continue;
      orig.set(n, n.nodeValue);
    }

    const o = orig.get(n);
    const t = o.trim();
    const v = lang === 'bn' ? o.replace(t, bn[t]) : o;
    if (n.nodeValue !== v) n.nodeValue = v;
  }

  document.querySelectorAll('[placeholder]').forEach((e) => {
    if (!e.dataset.en) e.dataset.en = e.placeholder;
    e.placeholder = lang === 'bn' ? bn[e.dataset.en] || e.dataset.en : e.dataset.en;
  });

  document.querySelectorAll('#languageSelect, #language').forEach((s) => {
    if (s.value !== lang) s.value = lang;
    if (!s.dataset.bound) {
      s.dataset.bound = '1';
      s.addEventListener('change', () => setLang(s.value));
    }
  });
}

run();
